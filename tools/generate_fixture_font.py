"""Regenerate the complete fixture UI Chinese font (Pillow + Microsoft YaHei)."""
from pathlib import Path
import re
s=Path(__file__).resolve().parents[1]/'9C-U_HTP100_SCREEN_Picture -100'
def put(p,t):p.write_text(t,encoding='utf-8')
# Create a compact, complete Chinese font for every string in this UI.
from PIL import Image, ImageDraw, ImageFont
for font_size in (28,36,48):
    font=ImageFont.truetype('C:/Windows/Fonts/msyh.ttc',font_size)
    ui=(s/'HardWare/Src/fixture_ui.c').read_text(encoding='utf-8')
    strings=re.findall(r'"([^"\n]*)"',ui)
    chars=sorted(set(''.join(strings)+''.join(chr(i) for i in range(32,127)))-{'\\'},key=ord)
    bitmap=[];dsc=['{0,0,0,0,0,0}'];code=[]
    for char in chars:
        x0,y0,x1,y1=font.getbbox(char,anchor='ls')
        w=max(x1-x0,0);h=max(y1-y0,0)
        im=Image.new('L',(max(w,1),max(h,1)))
        ImageDraw.Draw(im).text((-x0,-y0),char,font=font,fill=255,anchor='ls')
        pixels=[(p+8)//17 for p in im.getdata()] if w*h else []
        idx=len(bitmap)
        for i in range(0,len(pixels),2):bitmap.append((min(pixels[i],15)<<4)|(min(pixels[i+1],15) if i+1<len(pixels) else 0))
        dsc.append('{%d,%d,%d,%d,%d,%d}'%(idx,round(font.getlength(char)*16),w,h,x0,-y1))
        code.append(ord(char)-32)
    font_c='''/* Generated by tools/generate_fixture_font.py from Microsoft YaHei, 28px, 4bpp.
     * Contains every fixture UI glyph. Regenerate whenever UI text changes. */
    #include "lvgl.h"
    static const uint8_t bitmap[]={\n'''+','.join(map(str,bitmap))+'''};
    static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={'''+','.join(dsc)+'''};
    static const uint16_t unicode[]={'''+','.join(map(str,code))+'''};
    static const lv_font_fmt_txt_cmap_t cmap[]={ {
    .range_start=32,.range_length='''+str(max(code)+1)+''',.glyph_id_start=1,
    .unicode_list=unicode,.glyph_id_ofs_list=NULL,.list_length='''+str(len(code))+''',.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY} };
    static lv_font_fmt_txt_glyph_cache_t cache;
    static const lv_font_fmt_txt_dsc_t desc={.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmap,
    .kern_dsc=NULL,.kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0,.cache=&cache};
    const lv_font_t fixture_font28={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=38,.base_line=8,.dsc=&desc};
    '''
    font_c=font_c.replace('fixture_font28',f'fixture_font{font_size}').replace('28px',f'{font_size}px').replace('.line_height=38,.base_line=8',f'.line_height={font_size+10},.base_line={round(font_size*0.28)}')
    put(s/f'HardWare/Src/fixture_font{font_size}.c',font_c)
    print('Font glyphs:',len(chars),'bitmap bytes:',len(bitmap))
